#!/usr/bin/env node
// Copies the one-time secret file gate and crypto vectors of a brewpage-app checkout into mcp-server; --check fails on drift without writing.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const USAGE = 'Usage: node scripts/sync-secret-files.mjs [--check] <brewpage-app checkout>';
const DATA = 'backend/src/main/resources/secrets/file-types.json';
const MODEL = 'frontend/scripts/secret-files.mjs';
const VECTORS = 'frontend/test/fixtures/secret-vectors.json';
const root = resolve(import.meta.dirname, '..');
const GATE_OUT = resolve(root, 'mcp-server/src/compact/secret-file-types.ts');
const VECTORS_OUT = resolve(root, 'mcp-server/test/fixtures/secret-vectors.json');

const args = process.argv.slice(2);
const check = args.includes('--check');
const rest = args.filter((arg) => arg !== '--check');
if (rest.length !== 1) throw new Error(USAGE);
const app = resolve(rest[0]);
for (const path of [DATA, MODEL, VECTORS]) if (!existsSync(resolve(app, path))) throw new Error(`${app}: missing ${path}. ${USAGE}`);

// The app's own validator and compact model: the MCP gate embeds the same data as the browser's secret-files.js.
const { model } = await import(pathToFileURL(resolve(app, MODEL)).href);
const gate = model(JSON.parse(readFileSync(resolve(app, DATA), 'utf8')));
const vectors = readFileSync(resolve(app, VECTORS), 'utf8');
const parsed = JSON.parse(vectors);
if (!Array.isArray(parsed.seals) || !Array.isArray(parsed.keyChecks) || typeof parsed.keyCheckLabel !== 'string') {
  throw new Error(`${VECTORS}: expected keyCheckLabel, keyChecks and seals`);
}
const outputs = new Map([
  [GATE_OUT, `// Generated by scripts/sync-secret-files.mjs from brewpage-app ${DATA} (model of ${MODEL}); do not hand-edit.\n` +
    'import type { SecretFileModel } from "./secret-files.js";\n\n' +
    `/** File gate of one-time file secrets (app spec 7.2): ${gate.groups.length} groups, ${gate.denied.length} denied starts. */\n` +
    `export const SECRET_FILE_MODEL: SecretFileModel = ${JSON.stringify(gate, null, 2)};\n`],
  [VECTORS_OUT, vectors],
]);
const stale = [...outputs].filter(([path, bytes]) => !existsSync(path) || readFileSync(path, 'utf8') !== bytes).map(([path]) => path.slice(root.length + 1));
if (check && stale.length) {
  console.error(`Stale secret files: ${stale.join(', ')}; run node scripts/sync-secret-files.mjs <brewpage-app checkout>`);
  process.exit(1);
}
if (!check) for (const [path, bytes] of outputs) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, bytes);
}
console.log(`${check ? 'Secret files checked' : 'Secret files synced'}: ${gate.groups.length} groups, ${parsed.seals.length} seal and ${parsed.keyChecks.length} key-check vectors.`);
