#!/usr/bin/env node
// Copies the Page data cheat-sheet, its call-shapes line and the custom-domain status and problem tables from brewpage-app frontend/src into the MCP server.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const GUIDE_FILE = 'llms-full.txt';
const CALLS_FILE = 'llms.txt';
const SECTION = '## Page data';
const SUBSECTION = '### Browser SDK';
const FENCE = '```';
const FENCE_OPEN = '```text';
const CALLS_PREFIX = 'bp.state() -> s|null';
const MAX_LINES = 50;
const MAX_CHARS = 4096;
const DOMAIN_SECTION = '## Custom Domains';
const STATUSES_HEAD = 'Statuses (`status`):';
const PROBLEMS_HEAD = 'Problems (`problem`) and the fix:';
/** A row whose key holds a placeholder (`NOT_ELIGIBLE_<reason>`) names a family, not a code: left out. */
const PLACEHOLDER = /[<>]/;
const MAX_ROW_CHARS = 200;

/** Lines under the one `heading`, up to the next heading that matches `end`; headings inside fences never count. */
function section(lines, heading, end, where) {
  const found = [];
  let fenced = false;
  let open = false;
  for (const line of lines) {
    if (line.startsWith(FENCE)) fenced = !fenced;
    else if (!fenced && line === heading) {
      found.push([]);
      open = true;
      continue;
    } else if (!fenced && open && end.test(line)) open = false;
    if (open) found.at(-1).push(line);
  }
  if (found.length !== 1) throw new Error(`${where}: expected exactly one "${heading}" heading, found ${found.length}`);
  return found[0];
}

/** Bodies of the fenced `text` blocks among `lines`. */
function textBlocks(lines, where) {
  const blocks = [];
  let current;
  for (const line of lines) {
    if (current && line === FENCE) {
      blocks.push(current);
      current = undefined;
    } else if (current) current.push(line);
    else if (line === FENCE_OPEN) current = [];
  }
  if (current) throw new Error(`${where}: unclosed ${FENCE_OPEN} block`);
  return blocks;
}

/** One exported TypeScript constant under its doc comment. */
function constant(name, comment, expression) {
  return `/** ${comment} */\nexport const ${name} = ${expression};\n`;
}

/** `[key, text]` rows of the table after `head`: 2-space rows, deeper lines continue the row above, a blank line ends it. */
function table(lines, head, where) {
  const start = lines.indexOf(head);
  if (start < 0 || lines[start + 1] !== '') throw new Error(`${where}: no "${head}" line followed by a blank line`);
  const rows = [];
  for (const line of lines.slice(start + 2)) {
    if (line === '') break;
    if (/^ {2}\S/.test(line)) rows.push(line.trim());
    else if (/^ {3,}\S/.test(line) && rows.length) rows[rows.length - 1] += ` ${line.trim()}`;
    else throw new Error(`${where} "${head}": unexpected line ${JSON.stringify(line)}`);
  }
  const pairs = rows.map((row) => row.match(/^(\S+)\s{2,}(\S.*)$/)?.slice(1, 3));
  const bad = rows.find((row, i) => !pairs[i] || pairs[i][1].length > MAX_ROW_CHARS);
  if (!rows.length || bad !== undefined) throw new Error(
    `${where} "${head}": ${rows.length ? `row is not "<key>  <text>" within ${MAX_ROW_CHARS} chars: ${JSON.stringify(bad)}` : 'no rows'}`);
  if (new Set(pairs.map(([key]) => key)).size !== pairs.length) throw new Error(`${where} "${head}": duplicate key`);
  return pairs;
}

/** `Record<string, string>` literal, one row per line. */
function record(pairs) {
  return `{\n${pairs.map(([key, text]) => `  ${JSON.stringify(key)}: ${JSON.stringify(text)},\n`).join('')}}`;
}

const source = process.argv[2];
if (!source || process.argv.length > 3) throw new Error('Usage: node scripts/sync-guide.mjs <brewpage-app frontend/src dir>');
const read = (name) => readFileSync(resolve(source, name), 'utf8').split('\n');
const root = resolve(import.meta.dirname, '..');
const target = resolve(root, 'mcp-server/src/guides/page-data.ts');

const pageData = section(read(GUIDE_FILE), SECTION, /^## /, GUIDE_FILE);
const blocks = textBlocks(section(pageData, SUBSECTION, /^###? /, `${GUIDE_FILE} "${SECTION}"`), GUIDE_FILE);
if (blocks.length !== 1) throw new Error(`${GUIDE_FILE} "${SUBSECTION}": expected exactly one ${FENCE_OPEN} block, found ${blocks.length}`);
const guide = blocks[0];
const guideChars = [...`${guide.join('\n')}\n`].length;
if (guide.length === 0 || guide.length > MAX_LINES || guideChars > MAX_CHARS) throw new Error(
  `${GUIDE_FILE} cheat-sheet is ${guide.length} lines, ${guideChars} chars; the shared text allows 1-${MAX_LINES} lines, ${MAX_CHARS} chars`);

const calls = read(CALLS_FILE).filter((line) => line.startsWith(CALLS_PREFIX));
if (calls.length !== 1) throw new Error(`${CALLS_FILE}: expected exactly one line starting "${CALLS_PREFIX}", found ${calls.length}`);

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `// Generated by scripts/sync-guide.mjs from brewpage-app frontend/src (${GUIDE_FILE}, ${CALLS_FILE}); do not hand-edit.\n` +
  constant('PAGE_DATA_GUIDE', `Page data cheat-sheet: the text block under "${SECTION}" -> "${SUBSECTION}" of ${GUIDE_FILE}.`,
    `[\n${guide.map((line) => `  ${JSON.stringify(line)},\n`).join('')}].join("\\n") + "\\n"`) +
  constant('PAGE_DATA_CALLS', `Page script call shapes: the "${CALLS_PREFIX}" line of ${CALLS_FILE}.`, JSON.stringify(calls[0])));
console.log(`Page data guide synced: ${guide.length} lines, ${guideChars} chars; call-shapes line ${[...calls[0]].length} chars.`);

const domainTarget = resolve(root, 'mcp-server/src/guides/custom-domain.ts');
const domains = section(read(GUIDE_FILE), DOMAIN_SECTION, /^## /, GUIDE_FILE);
const where = `${GUIDE_FILE} "${DOMAIN_SECTION}"`;
const statuses = table(domains, STATUSES_HEAD, where);
const problems = table(domains, PROBLEMS_HEAD, where).filter(([key]) => !PLACEHOLDER.test(key));
if (statuses.some(([key]) => PLACEHOLDER.test(key)) || !problems.length) throw new Error(`${where}: statuses or problems are not plain codes`);
writeFileSync(domainTarget, `// Generated by scripts/sync-guide.mjs from brewpage-app frontend/src (${GUIDE_FILE}); do not hand-edit.\n` +
  constant('DOMAIN_STATUSES: Record<string, string>', `Custom-domain statuses: the "${STATUSES_HEAD}" table under "${DOMAIN_SECTION}" of ${GUIDE_FILE}.`,
    record(statuses)) +
  constant('DOMAIN_PROBLEMS: Record<string, string>',
    `Custom-domain problems and fixes: the "${PROBLEMS_HEAD}" table of the same section; rows with a <placeholder> key left out.`, record(problems)));
console.log(`Custom-domain tables synced: ${statuses.length} statuses, ${problems.length} problems.`);
