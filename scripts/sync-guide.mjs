#!/usr/bin/env node
// Copies the Page data cheat-sheet and call-shapes line from brewpage-app frontend/src into the MCP server.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const GUIDE_FILE = 'llms-full.txt';
const CALLS_FILE = 'llms.txt';
const SECTION = '## Page data';
const SUBSECTION = '### Browser SDK';
const FENCE = '```';
const FENCE_OPEN = '```text';
const CALLS_PREFIX = 'bp.state() -> s|null';
const MAX_LINES = 50;
const MAX_CHARS = 4096;

/** Lines under the one `heading`, up to the next heading that matches `end`; headings inside fences never count. */
function section(lines, heading, end, where) {
  const found = [];
  let fenced = false;
  let open = false;
  for (const line of lines) {
    if (line.startsWith(FENCE)) fenced = !fenced;
    else if (!fenced && line === heading) {
      found.push([]);
      open = true;
      continue;
    } else if (!fenced && open && end.test(line)) open = false;
    if (open) found.at(-1).push(line);
  }
  if (found.length !== 1) throw new Error(`${where}: expected exactly one "${heading}" heading, found ${found.length}`);
  return found[0];
}

/** Bodies of the fenced `text` blocks among `lines`. */
function textBlocks(lines, where) {
  const blocks = [];
  let current;
  for (const line of lines) {
    if (current && line === FENCE) {
      blocks.push(current);
      current = undefined;
    } else if (current) current.push(line);
    else if (line === FENCE_OPEN) current = [];
  }
  if (current) throw new Error(`${where}: unclosed ${FENCE_OPEN} block`);
  return blocks;
}

/** One exported TypeScript constant under its doc comment. */
function constant(name, comment, expression) {
  return `/** ${comment} */\nexport const ${name} = ${expression};\n`;
}

const source = process.argv[2];
if (!source || process.argv.length > 3) throw new Error('Usage: node scripts/sync-guide.mjs <brewpage-app frontend/src dir>');
const read = (name) => readFileSync(resolve(source, name), 'utf8').split('\n');
const root = resolve(import.meta.dirname, '..');
const target = resolve(root, 'mcp-server/src/guides/page-data.ts');

const pageData = section(read(GUIDE_FILE), SECTION, /^## /, GUIDE_FILE);
const blocks = textBlocks(section(pageData, SUBSECTION, /^###? /, `${GUIDE_FILE} "${SECTION}"`), GUIDE_FILE);
if (blocks.length !== 1) throw new Error(`${GUIDE_FILE} "${SUBSECTION}": expected exactly one ${FENCE_OPEN} block, found ${blocks.length}`);
const guide = blocks[0];
const guideChars = [...`${guide.join('\n')}\n`].length;
if (guide.length === 0 || guide.length > MAX_LINES || guideChars > MAX_CHARS) throw new Error(
  `${GUIDE_FILE} cheat-sheet is ${guide.length} lines, ${guideChars} chars; the shared text allows 1-${MAX_LINES} lines, ${MAX_CHARS} chars`);

const calls = read(CALLS_FILE).filter((line) => line.startsWith(CALLS_PREFIX));
if (calls.length !== 1) throw new Error(`${CALLS_FILE}: expected exactly one line starting "${CALLS_PREFIX}", found ${calls.length}`);

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `// Generated by scripts/sync-guide.mjs from brewpage-app frontend/src (${GUIDE_FILE}, ${CALLS_FILE}); do not hand-edit.\n` +
  constant('PAGE_DATA_GUIDE', `Page data cheat-sheet: the text block under "${SECTION}" -> "${SUBSECTION}" of ${GUIDE_FILE}.`,
    `[\n${guide.map((line) => `  ${JSON.stringify(line)},\n`).join('')}].join("\\n") + "\\n"`) +
  constant('PAGE_DATA_CALLS', `Page script call shapes: the "${CALLS_PREFIX}" line of ${CALLS_FILE}.`, JSON.stringify(calls[0])));
console.log(`Page data guide synced: ${guide.length} lines, ${guideChars} chars; call-shapes line ${[...calls[0]].length} chars.`);
