#!/usr/bin/env node
// Generates MCP guides from the maintained BrewPage LLM reference.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const GUIDE_FILE = 'llms-full.txt';
const SECTION = '## Page data';
const SUBSECTION = '### Browser SDK';
const PAGE_DATA_MCP = '### Manage Page data with MCP';
const PACKAGES = '### Framework packages';
const FENCE = '```';
const FENCE_OPEN = '```text';
const CALLS_PREFIX = 'bp.state() -> s|null';
const MAX_LINES = 50;
const MAX_CHARS = 4096;
const DOMAIN_SECTION = '## Custom Domains';
const DOMAIN_MCP = '### Connect a domain with MCP';
const STATUSES_HEAD = 'Statuses (`status`):';
const PROBLEMS_HEAD = 'Problems (`problem`) and the fix:';
/** A row whose key holds a placeholder (`NOT_ELIGIBLE_<reason>`) names a family, not a code: left out. */
const PLACEHOLDER = /[<>]/;
const MAX_ROW_CHARS = 200;
const TEMPLATES_SECTION = '## Templates';
const TEMPLATES_MCP = '### Copy a template with MCP';
const TEMPLATES_FIND = 'GET https://brewpage.app/api/templates?q=';
const RECIPE_SECTIONS = [
  ['publishing.ts', 'PUBLISHING_GUIDE', '## Workflows', '### Publishing a page'],
  ['account.ts', 'ACCOUNT_GUIDE', '## Tooling', '### Connect a BrewPage account'],
];
const GENERATED = `// Generated by scripts/sync-guide.mjs from brewpage-app frontend/src (${GUIDE_FILE}); do not hand-edit.\n`;

/** Lines under the one `heading`, up to the next heading that matches `end`; headings inside fences never count. */
function section(lines, heading, end, where) {
  const found = [];
  let fenced = false;
  let open = false;
  for (const line of lines) {
    if (line.startsWith(FENCE)) fenced = !fenced;
    else if (!fenced && line === heading) {
      found.push([]);
      open = true;
      continue;
    } else if (!fenced && open && end.test(line)) open = false;
    if (open) found.at(-1).push(line);
  }
  if (found.length !== 1) throw new Error(`${where}: expected exactly one "${heading}" heading, found ${found.length}`);
  return found[0];
}

/** Bodies of the fenced `text` blocks among `lines`. */
function textBlocks(lines, where) {
  const blocks = [];
  let current;
  for (const line of lines) {
    if (current && line === FENCE) {
      blocks.push(current);
      current = undefined;
    } else if (current) current.push(line);
    else if (line === FENCE_OPEN) current = [];
  }
  if (current) throw new Error(`${where}: unclosed ${FENCE_OPEN} block`);
  return blocks;
}

/** One exported TypeScript constant under its doc comment. */
function constant(name, comment, expression) {
  return `/** ${comment} */\nexport const ${name} = ${expression};\n`;
}

/** `[key, text]` rows of the table after `head`: 2-space rows, deeper lines continue the row above, a blank line ends it. */
function table(lines, head, where) {
  const start = lines.indexOf(head);
  if (start < 0 || lines[start + 1] !== '') throw new Error(`${where}: no "${head}" line followed by a blank line`);
  const rows = [];
  for (const line of lines.slice(start + 2)) {
    if (line === '') break;
    if (/^ {2}\S/.test(line)) rows.push(line.trim());
    else if (/^ {3,}\S/.test(line) && rows.length) rows[rows.length - 1] += ` ${line.trim()}`;
    else throw new Error(`${where} "${head}": unexpected line ${JSON.stringify(line)}`);
  }
  const pairs = rows.map((row) => row.match(/^(\S+)\s{2,}(\S.*)$/)?.slice(1, 3));
  const bad = rows.find((row, i) => !pairs[i] || pairs[i][1].length > MAX_ROW_CHARS);
  if (!rows.length || bad !== undefined) throw new Error(
    `${where} "${head}": ${rows.length ? `row is not "<key>  <text>" within ${MAX_ROW_CHARS} chars: ${JSON.stringify(bad)}` : 'no rows'}`);
  if (new Set(pairs.map(([key]) => key)).size !== pairs.length) throw new Error(`${where} "${head}": duplicate key`);
  return pairs;
}

/** `Record<string, string>` literal, one row per line. */
function record(pairs) {
  return `{\n${pairs.map(([key, text]) => `  ${JSON.stringify(key)}: ${JSON.stringify(text)},\n`).join('')}}`;
}

function textLiteral(lines) {
  return `[\n${lines.map((line) => `  ${JSON.stringify(line)},\n`).join('')}].join("\\n") + "\\n"`;
}

function recipe(parent, heading, where) {
  const text = section(parent, heading, /^###? /, where).join('\n').trim();
  if (!text || [...text].length >= MAX_CHARS) throw new Error(`${where}: recipe "${heading}" is empty or too long`);
  return text;
}

const args = process.argv.slice(2);
const check = args[0] === '--check';
const [source, ...extra] = check ? args.slice(1) : args;
if (!source || source.startsWith('--') || extra.length) {
  throw new Error('Usage: node scripts/sync-guide.mjs [--check] <brewpage-app frontend/src dir>');
}
const lines = readFileSync(resolve(source, GUIDE_FILE), 'utf8').split('\n');
const targetDir = resolve(import.meta.dirname, '../mcp-server/src/guides');
const outputs = new Map();
const summaries = [];
const tooling = section(lines, '## Tooling', /^## /, GUIDE_FILE);

const pageData = section(lines, SECTION, /^## /, GUIDE_FILE);
const blocks = textBlocks(section(pageData, SUBSECTION, /^###? /, `${GUIDE_FILE} "${SECTION}"`), GUIDE_FILE);
if (blocks.length !== 1) throw new Error(`${GUIDE_FILE} "${SUBSECTION}": expected exactly one ${FENCE_OPEN} block, found ${blocks.length}`);
const guide = blocks[0];
const guideChars = [...`${guide.join('\n')}\n`].length;
if (guide.length === 0 || guide.length > MAX_LINES || guideChars > MAX_CHARS) throw new Error(
  `${GUIDE_FILE} cheat-sheet is ${guide.length} lines, ${guideChars} chars; the shared text allows 1-${MAX_LINES} lines, ${MAX_CHARS} chars`);

const packages = recipe(pageData, PACKAGES, `${GUIDE_FILE} "${SECTION}"`);
const calls = lines.filter((line) => line.startsWith(CALLS_PREFIX));
if (calls.length !== 1) throw new Error(`${GUIDE_FILE}: expected exactly one line starting "${CALLS_PREFIX}", found ${calls.length}`);

outputs.set('page-data.ts', GENERATED +
  constant('PAGE_DATA_GUIDE', `Page data cheat-sheet: the text block under "${SECTION}" -> "${SUBSECTION}" of ${GUIDE_FILE}.`,
    textLiteral(guide)) +
  constant('PAGE_DATA_CALLS', `Page script call shapes: the "${CALLS_PREFIX}" line of ${GUIDE_FILE}.`, JSON.stringify(calls[0])) +
  constant('PAGE_DATA_MCP_GUIDE', `Compact owner recipe from "${PAGE_DATA_MCP}".`,
    textLiteral(recipe(tooling, PAGE_DATA_MCP, GUIDE_FILE).split('\n'))) +
  constant('PAGE_DATA_PACKAGES_GUIDE', `The "${SECTION}" -> "${PACKAGES}" section of ${GUIDE_FILE}, heading included.`,
    textLiteral([PACKAGES, '', ...packages.split('\n')])));
summaries.push(`Page data guide: ${guide.length} lines, ${guideChars} chars. Call shapes: ${[...calls[0]].length} chars. ` +
  `Framework packages: ${[...packages].length + 1} chars.`);

const domains = section(lines, DOMAIN_SECTION, /^## /, GUIDE_FILE);
const where = `${GUIDE_FILE} "${DOMAIN_SECTION}"`;
const statuses = table(domains, STATUSES_HEAD, where);
const problems = table(domains, PROBLEMS_HEAD, where).filter(([key]) => !PLACEHOLDER.test(key));
if (statuses.some(([key]) => PLACEHOLDER.test(key)) || !problems.length) throw new Error(`${where}: statuses or problems are not plain codes`);
outputs.set('custom-domain.ts', GENERATED +
  constant('DOMAIN_STATUSES: Record<string, string>', `Custom-domain statuses: the "${STATUSES_HEAD}" table under "${DOMAIN_SECTION}" of ${GUIDE_FILE}.`,
    record(statuses)) +
  constant('DOMAIN_PROBLEMS: Record<string, string>',
    `Custom-domain problems and fixes: the "${PROBLEMS_HEAD}" table of the same section; rows with a <placeholder> key left out.`, record(problems)) +
  constant('DOMAIN_MCP_GUIDE', `Compact owner recipe from "${DOMAIN_MCP}".`, textLiteral(recipe(tooling, DOMAIN_MCP, GUIDE_FILE).split('\n'))));
summaries.push(`Custom-domain tables: ${statuses.length} statuses, ${problems.length} problems.`);

const templatesWhere = `${GUIDE_FILE} "${TEMPLATES_SECTION}"`;
const templateLines = section(lines, TEMPLATES_SECTION, /^## /, GUIDE_FILE);
const templatesMcp = recipe(templateLines, TEMPLATES_MCP, templatesWhere);
const catalogueRows = templateLines.filter((line) => /^ {2}\S/.test(line)).length;
const templates = templateLines.slice(0, templateLines.indexOf(TEMPLATES_MCP)).filter((line) => !/^ {2}\S/.test(line))
  .filter((line, i, all) => line !== '' || (i > 0 && all[i - 1] !== '')).join('\n').trim();
const restStep = templates.indexOf('\n4. `POST`');
const compactTemplates = `${templates.slice(0, restStep)}\n\n${templatesMcp}`;
const templatesChars = [...`${templates}\n`].length;
if (!catalogueRows || restStep < 0 || !templates.includes(TEMPLATES_FIND) || !templates.includes('publishUrl') ||
  templatesChars > MAX_CHARS || [...compactTemplates].length >= MAX_CHARS) throw new Error(
  `${templatesWhere}: expected the catalogue table, "${TEMPLATES_FIND}" and \`publishUrl\` within ${MAX_CHARS} chars (${templatesChars})`);
outputs.set('templates.ts', GENERATED +
  `const TEMPLATE_PREPARATION = ${textLiteral(templates.slice(0, restStep).split('\n'))};\n` +
  constant('TEMPLATES_GUIDE', 'Legacy template preparation and REST workflow.',
    'TEMPLATE_PREPARATION + ' + textLiteral(templates.slice(restStep + 1).split('\n'))) +
  constant('TEMPLATES_MCP_GUIDE', `Template preparation and the "${TEMPLATES_MCP}" recipe.`,
    'TEMPLATE_PREPARATION + "\\n" + ' + textLiteral(templatesMcp.split('\n'))));
summaries.push(`Templates guide: ${templatesChars} chars, ${catalogueRows} catalogue rows left out.`);

for (const [filename, name, heading, subheading] of RECIPE_SECTIONS) {
  const parent = section(lines, heading, /^## /, GUIDE_FILE);
  const text = recipe(parent, subheading, `${GUIDE_FILE} "${heading}"`);
  const chars = [...text].length + 1;
  outputs.set(filename, GENERATED + constant(name, `Recipe under "${heading}" -> "${subheading}" of ${GUIDE_FILE}.`, textLiteral(text.split('\n'))));
  summaries.push(`${filename}: ${chars} chars.`);
}

if (check) {
  const stale = [...outputs].filter(([name, bytes]) => {
    const path = resolve(targetDir, name);
    return !existsSync(path) || readFileSync(path, 'utf8') !== bytes;
  }).map(([name]) => name);
  if (stale.length) throw new Error(`Regenerate stale MCP guides: ${stale.join(', ')}`);
} else {
  mkdirSync(targetDir, { recursive: true });
  for (const [name, bytes] of outputs) writeFileSync(resolve(targetDir, name), bytes);
}
console.log([check ? 'MCP guides checked.' : 'MCP guides synced.', ...summaries].join('\n'));
